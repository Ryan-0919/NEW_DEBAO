export const downloadQuestionImportTemplate = (kind: QuestionImportTemplateKind) => {
  const rows = rowsByKind[kind];
  const columns = columnsByKind[kind];
  const worksheet = XLSX.utils.json_to_sheet(rows, { header: columns });
  worksheet["!cols"] = columns.map((column) => ({ wch: Math.max(12, Math.min(28, column.length * 2 + 8)) }));
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, "导入模板");
  XLSX.writeFile(workbook, fileNameByKind[kind]);
};
